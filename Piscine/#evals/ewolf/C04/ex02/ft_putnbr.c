#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	cur;

	cur = '0';
	if (nb == -2147483648)
		write(1, "-2147483648", 11);
	else
	{
		if (nb < 0)
		{
			write(1, "-", 1);
			nb *= -1;
		}
		if (nb > 9)
			ft_putnbr((int)nb / 10);
		cur = (nb % 10) + '0';
		write(1, &cur, 1);
	}
}

